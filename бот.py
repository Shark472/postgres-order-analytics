print("🤖 Система: Консольный бот запущен и готов к работе!")
print("🤖 Бот: Привет! Я твой локальный бот на Python. Напиши мне что-нибудь!")
print("(Чтобы выключить бота, просто напиши слово: выход)\n")

while True:
    # Заставляем бота ждать текстовое сообщение в консоли
    user_text = input("Вы: ")

    # Обрабатываем команду выхода
    if user_text.lower() == "выход":
        print("🤖 Бот: До встречи! Выключаюсь...")
        break

    # Обрабатываем команды /start и /help (как в настоящем Telegram)
    elif user_text.lower() in ["/start", "/help", "старт", "привет"]:
        print("🤖 Бот: Я умею повторять твои фразы ГРОМКО. Попробуй написать любой текст!")

    # Обрабатываем обычный текст (наш Эхо-эффект)
    else:
        # Переводим текст в верхний регистр (заглавные буквы)
        echo_text = user_text.upper()
        print(f"🤖 Бот: Ты написал: {echo_text}")

    print("-" * 30)  # Красивый разделитель реплик

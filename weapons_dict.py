import random

# Наше оружие (Словарь)
sword = {
    "название": "Меч Дракона",
    "урон": 40,
    "прочность": 100
}

# Характеристики босса (тоже Словарь!)
boss = {
    "имя": "Демон Капра",
    "здоровье": 150
}

print(f"⚔️ Начинается битва! Перед тобой {boss['имя']} ({boss['здоровье']} HP)!")
print(f"В твоих руках {sword['название']} с базовым уроном {sword['урон']}.\n")

while boss["здоровье"] > 0:
    input("Нажми Enter, чтобы нанести удар мечом...")

    # Генерируем случайный бонус к урону (от 1 до 20 единиц)
    crit_bonus = random.randint(1, 20)

    # Считаем итоговый урон: база из словаря + бонус
    final_damage = sword["урон"] + crit_bonus

    # Наносим урон: уменьшаем здоровье босса в словаре
    boss["здоровье"] = boss["здоровье"] - final_damage

    # Логика прочности: меч тупится на 10 единиц за удар
    sword["прочность"] = sword["прочность"] - 10

    print(f"💥 Ты нанес {final_damage} урона! (Бонус крита: +{crit_bonus})")

    # Защита от отрицательного здоровья (чтобы не писать HP: -20)
    if boss["здоровье"] < 0:
        boss["здоровье"] = 0

    print(f"👹 У {boss['имя']} осталось {boss['здоровье']} HP.")
    print(f"🛡️ Прочность твоего меча: {sword['прочность']}/100")
    print("-" * 35)

print(f"🎉 Победа! {boss['имя']} повержен! Твой {sword['название']} выдержал этот бой.")
